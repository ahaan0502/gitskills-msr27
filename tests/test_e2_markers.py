from gitskills.e2_markers import (
    MARKER_SPEC_VERSION,
    author_type_marker,
    marker_matches,
    normalize_marker_text,
)


def test_marker_spec_is_versioned():
    assert MARKER_SPEC_VERSION == "e2-marker-spec-v1"


def test_normalization_is_case_and_unicode_stable():
    assert normalize_marker_text("  Generated\u200b  BY  ") == "generated by"


def test_message_generated_by_is_high_specificity():
    matches = marker_matches("Generated by an automated agent", "message")
    assert "message_generated_by" in {item["reason_code"] for item in matches}
    assert any(item["specificity"] == "high" for item in matches)


def test_content_requires_agent_subject_for_high_specificity():
    assert marker_matches("Generated by an agent", "content")[0]["reason_code"] == "content_generated_by"
    assert marker_matches("Generated by a person", "content") == []


def test_workflow_marker_is_separate_from_commit_message_marker():
    assert marker_matches("An agent will create this file", "workflow")
    assert marker_matches("An agent will create this file", "message") == []


def test_author_type_bot_is_automated_marker():
    result = author_type_marker("ProgrammaticAccessBot")
    assert result == {"reason_code": "author_type_automated", "family": "identity", "specificity": "high"}


def test_human_like_author_type_is_not_positive_agent_evidence():
    result = author_type_marker("User")
    assert result["reason_code"] == "author_type_non_automated"
    assert author_type_marker("") is None
